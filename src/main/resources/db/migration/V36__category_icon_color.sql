-- ============================================================================
-- 有余(youyu) 分类自定义配色：分类新增 icon_color 字段
-- MySQL 8.x / utf8mb4
--
-- 背景：
--   分类磁贴原先统一灰底灰图标，表达力弱。改为「实色圆角磁贴 + 白色描边图标」，
--   分类持久化背景色 hex(#RRGGBB)（用户可在新建/编辑分类时选择）。
--
-- 本迁移（纯增量）：
--   1. categories 增加 icon_color VARCHAR(9) NULL（不回填、不改动既有列）。
--      NULL = 使用默认色 #12a150（由渲染侧兜底）。
-- ============================================================================

ALTER TABLE categories ADD COLUMN icon_color VARCHAR(9) NULL COMMENT '分类图标背景色 hex(#RRGGBB)';

-- ============================================================================
-- 有余(youyu) 账户发卡银行 / 卡号
-- issuing_bank：发卡银行名称（可空，仅储蓄卡/信用卡有意义），存中文行名如“招商银行”。
-- card_no：卡号或尾号（可空，建议仅存后四位），仅用于区分同行多张卡。
-- ============================================================================
ALTER TABLE accounts
    ADD COLUMN issuing_bank VARCHAR(40) NULL COMMENT '发卡银行(可空,储蓄卡/信用卡)',
    ADD COLUMN card_no      VARCHAR(30) NULL COMMENT '卡号/尾号(可空)';

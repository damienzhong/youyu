-- ============================================================================
-- 余额调整回归「账户级」：历史「余额调整」补差流水脱离账本（不计入账本收支/报表）。
--
-- 余额调整是对账户余额的校准（账户为用户级资产），只应出现在「账户流水」，不应计入任何账本。
-- 与转账类似将 ledger_id 置空；但 ck_tx_fields 约束要求收支必须带分类，故保留 category_id。
-- 「收支类型 + ledger_id 为空」即余额调整，前端据此在账户流水中识别与展示。
-- 识别依据：交易引用系统生成的顶级「余额调整」分类。
-- ============================================================================
UPDATE transactions t
JOIN categories c ON t.category_id = c.id
SET t.ledger_id = NULL
WHERE c.parent_id IS NULL AND c.name = '余额调整';

-- ============================================================================
-- 有余(youyu) 协作账本隐私修复：账户余额默认不向其他成员显示
-- MySQL 8.x / utf8mb4
--
-- 背景：
--   account_ledger.show_balance 早期默认 1（显示真实余额），导致把账户暴露进协作
--   账本后，其他成员在记账选账户等处直接看到该账户的真实余额，泄漏了账户 owner 的
--   资产隐私。账本本身不持有资产，仅用于记账；账户余额属于账户 owner 的私有信息。
--
-- 本迁移：
--   1. 将列默认值改为 0（隐私优先，与实体/服务层新默认一致）。
--   2. 把已存在关联行的 show_balance 一并重置为 0，立即止血——需要共享余额的账户由
--      owner 在「资产 - 账户 - 参与账本」中手动重新开启。
-- ============================================================================

-- 1. 列默认值改为不显示余额。
ALTER TABLE account_ledger
    MODIFY COLUMN show_balance TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '是否对其他成员显示真实余额(隐私优先,默认否;owner 始终可见自己余额)';

-- 2. 重置已存在关联行：一律不向其他成员显示余额。
UPDATE account_ledger SET show_balance = 0 WHERE show_balance = 1;
